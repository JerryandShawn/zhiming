from typing import Any, ContextManager, Protocol


class RepositoryPort(Protocol):
    def transaction(self, owner: str | None = None) -> ContextManager[Any]: ...
    def ensure_owner(self, owner: str, **kwargs) -> dict: ...
    def assert_scope(self, owner: str, subject: str = 'self') -> dict: ...
    def get(self, owner: str, kind: str, entity_id: str, **kwargs) -> dict: ...
    def list(self, owner: str, kind: str, **kwargs) -> list[dict]: ...
    def put(self, owner: str, kind: str, entity_id: str, data: dict, **kwargs) -> dict: ...
    def update(self, owner: str, kind: str, entity_id: str, changes: dict, *, expected_revision: int, **kwargs) -> dict: ...
    def versions(self, owner: str, subject: str, case_ids: list[str]) -> dict[str, int]: ...
    def verify_versions(self, owner: str, versions: dict[str, int]) -> bool: ...
    def fetch_run(self, owner: str, run_id: str) -> dict: ...
