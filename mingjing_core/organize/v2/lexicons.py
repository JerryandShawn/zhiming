def _build() -> dict[str, dict[str, float]]:
    result = {}
    for space in DEFAULT_SPACES:
        words = sorted(set(space.keywords) | set(_EXTRA[space.id].split()) | set(_BROAD[space.id].split()))
        result[space.id] = {
            word.casefold(): (0.35 if word in _SINGLE else 0.85 if word in _WEAK else 1.75) for word in words
        }
    return result


