"""An in-process fake platform, never an HTTP server or a real transport."""

import base64
from copy import deepcopy
import hashlib
import json

from Crypto.Cipher import AES
from Crypto.Util.Padding import pad

from mingjing_core.adapters.channels.cards_official_v3 import validate_card


class FakeFeishu:
    def __init__(self):
        self.cards = {}
        self.effects = []

    def send(self, card, open_id):
        document = validate_card(card)
        message_id = f"synthetic_message_{len(self.cards) + 1}"
        self.cards[message_id] = (open_id, deepcopy(document))
        return message_id

    def callback(
        self,
        *,
        message_id,
        action_token,
        event_id="synthetic_event",
        app_id="synthetic_app",
        open_id=None,
        chat_id="synthetic_chat",
        verification_token="synthetic_verification",
    ):
        actor = open_id or self.cards[message_id][0]
        return {
            "schema": "2.0",
            "header": {
                "event_id": event_id,
                "app_id": app_id,
                "token": verification_token,
                "event_type": "card.action.trigger",
            },
            "event": {
                "operator": {"open_id": actor},
                "context": {"open_chat_id": chat_id, "open_message_id": message_id},
                "action": {"tag": "button", "value": {"t": action_token}},
            },
        }

    @staticmethod
    def plaintext(document):
        return json.dumps(document, ensure_ascii=False, separators=(",", ":")).encode()

    @staticmethod
    def webhook(
        document, *, now, encrypt_key="synthetic_encrypt", nonce="synthetic_nonce"
    ):
        # Deterministic IV is fixture-only. Production receives IVs generated by Feishu.
        iv = bytes(range(16))
        key = hashlib.sha256(encrypt_key.encode()).digest()
        encrypted = iv + AES.new(key, AES.MODE_CBC, iv).encrypt(
            pad(FakeFeishu.plaintext(document), 16)
        )
        raw = FakeFeishu.plaintext({"encrypt": base64.b64encode(encrypted).decode()})
        timestamp = str(int(now.timestamp()))
        signature = hashlib.sha256(
            (timestamp + nonce + encrypt_key).encode() + raw
        ).hexdigest()
        return dict(raw=raw, timestamp=timestamp, nonce=nonce, signature=signature)

    def execute(self, command, *, uncertain=False):
        self.effects.append(command.operation_id)
        if uncertain:
            raise TimeoutError("synthetic uncertainty after side effect")
